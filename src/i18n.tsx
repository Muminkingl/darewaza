const dictionaries = { ckb, en, ar };
type I18n = {
  locale: Locale;
  ready: boolean;
  setLocale: (locale: Locale) => void;
  t: (key: Key) => string;
  rtl: boolean;
  row: ViewStyle;
  align: TextStyle;
};
const Context = createContext<I18n>(null!);
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setValue] = useState<Locale>("ckb");
  const [ready, setReady] = useState(false);
  useEffect(() => {
    AsyncStorage.getItem("darewaza.language")
      .then((v) => {
        if (v && v in dictionaries) setValue(v as Locale);
      })
      .catch(() => {})
      .finally(() => setReady(true));
  }, []);
  const value = useMemo<I18n>(
    () => ({
      locale,
      ready,
      setLocale(next) {
        setValue(next);
        void AsyncStorage.setItem("darewaza.language", next).catch(() => {});
      },
      t: (key) => dictionaries[locale][key],
      rtl: locale !== "en",
      row: { flexDirection: locale === "en" ? "row" : "row-reverse" },
      align: {
        textAlign: locale === "en" ? "left" : "right",
        writingDirection: locale === "en" ? "ltr" : "rtl",
      },
    }),
    [locale, ready],
  );
  return <Context.Provider value={value}>{children}</Context.Provider>;
}
